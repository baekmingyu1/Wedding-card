import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(root, "assets", "opening");
const outputDir = join(sourceDir, "frames");
const widths = [480, 768, 1024, 1600];
const mobileWidths = widths.filter((width) => width <= 1024);
const filenames = (await readdir(sourceDir)).filter((name) => /^DSC\d+\.jpg$/i.test(name)).sort();
if (!filenames.length) throw new Error("assets/opening/에 DSC*.jpg 원본 사진이 필요합니다.");
await mkdir(outputDir, { recursive: true });

const manifest = [];
for (const [index, name] of filenames.entries()) {
  const id = String(index + 1).padStart(2, "0");
  const input = join(sourceDir, name);
  const metadata = await sharp(input).metadata();
  const candidates = [];
  for (const width of widths.filter((value) => value <= metadata.width)) {
    const buffer = await sharp(input).rotate().resize({ width, withoutEnlargement: true })
      .webp({ quality: width === 1600 ? 72 : 74, effort: 6 }).toBuffer();
    const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 10);
    const filename = `${id}-${width}-${hash}.webp`;
    await writeFile(join(outputDir, filename), buffer);
    candidates.push({ width, url: `assets/opening/frames/${filename}`, bytes: buffer.length });
  }
  const blurBuffer = await sharp(input).rotate().resize({ width: 96, withoutEnlargement: true })
    .blur(5).webp({ quality: 45, effort: 6 }).toBuffer();
  const blurHash = createHash("sha256").update(blurBuffer).digest("hex").slice(0, 10);
  const blurName = `${id}-blur-${blurHash}.webp`;
  await writeFile(join(outputDir, blurName), blurBuffer);
  const desktop = candidates.map(({ url, width }) => `${url} ${width}w`).join(", ");
  const mobile = candidates.filter(({ width }) => mobileWidths.includes(width))
    .map(({ url, width }) => `${url} ${width}w`).join(", ");
  const largest = candidates.at(-1);
  manifest.push({ id, src: largest.url, srcset: desktop, mobileSrcset: mobile,
    blur: `assets/opening/frames/${blurName}`, width: largest.width,
    height: Math.round(metadata.height * largest.width / metadata.width) });
  console.log(`${id} ${name}: ${candidates.map(({ width, bytes }) => `${width}w ${Math.round(bytes / 1024)} KB`).join(", ")}`);
}

const manifestPath = join(root, "opening-images.js");
await writeFile(manifestPath, `// Generated by npm run images. Edit the source JPGs, then regenerate.\nwindow.OPENING_IMAGES = ${JSON.stringify(manifest, null, 2)};\n`);

const first = manifest[0];
const mobileDefault = first.mobileSrcset.split(", ").at(-1).split(" ")[0];
const preload = [
  "<!-- OPENING_PRELOAD_START -->",
  `  <link rel="preload" as="image" media="(max-width: 760px)" href="${mobileDefault}" imagesrcset="${first.mobileSrcset}" imagesizes="135vw" fetchpriority="high">`,
  `  <link rel="preload" as="image" media="(min-width: 761px)" href="${first.src}" imagesrcset="${first.srcset}" imagesizes="100vw" fetchpriority="high">`,
  "  <!-- OPENING_PRELOAD_END -->"
].join("\n");
const htmlPath = join(root, "index.html");
const html = await readFile(htmlPath, "utf8");
if (!/<!-- OPENING_PRELOAD_START -->[\s\S]*?<!-- OPENING_PRELOAD_END -->/.test(html)) {
  throw new Error("index.html의 opening preload marker를 찾을 수 없습니다.");
}
await writeFile(htmlPath, html.replace(/<!-- OPENING_PRELOAD_START -->[\s\S]*?<!-- OPENING_PRELOAD_END -->/, preload));

console.log(`Generated ${manifest.length} responsive opening photos.`);
